const originalText = new WeakMap();
const originalAttributes = new WeakMap();
let observer = null;
let currentLanguage = "vi";

const translateValue = (value, translations) => {
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const key = value.trim();
  const translated = translations[key];
  const patternMatch = !translated && translations === TEXT_TRANSLATIONS
    ? PATTERN_TRANSLATIONS.find(([pattern]) => pattern.test(key))
    : null;

  if (translated) {
    return `${leading}${translated}${trailing}`;
  }

  if (patternMatch) {
    const [pattern, replacement] = patternMatch;
    return `${leading}${key.replace(pattern, replacement)}${trailing}`;
  }

  return value;
};

const translateTextNode = (node) => {
  if (!node.nodeValue.trim()) return;

  if (!originalText.has(node)) {
    originalText.set(node, node.nodeValue);
  }

  const source = originalText.get(node);
  const nextValue = currentLanguage === "en"
    ? translateValue(source, TEXT_TRANSLATIONS)
    : source;

  if (node.nodeValue !== nextValue) {
    node.nodeValue = nextValue;
  }
};

const translateElementAttributes = (element) => {
  ["placeholder", "aria-label", "title"].forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;

    const attributeStore = originalAttributes.get(element) || {};
    if (!attributeStore[attribute]) {
      attributeStore[attribute] = element.getAttribute(attribute);
      originalAttributes.set(element, attributeStore);
    }

    const source = attributeStore[attribute];
    const nextValue = currentLanguage === "en"
      ? translateValue(source, PLACEHOLDER_TRANSLATIONS)
      : source;

    if (element.getAttribute(attribute) !== nextValue) {
      element.setAttribute(attribute, nextValue);
    }
  });
};

const walkAndTranslate = (root = document.body) => {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }

  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;

  if (root.nodeType === Node.ELEMENT_NODE) {
    translateElementAttributes(root);
  }

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  let node = walker.nextNode();

  while (node) {
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node);
    } else {
      translateElementAttributes(node);
    }
    node = walker.nextNode();
  }
};

const ensureObserver = () => {
  if (observer || !document.body) return;

  observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      mutation.addedNodes.forEach((node) => walkAndTranslate(node));

      if (mutation.type === "characterData") {
        translateTextNode(mutation.target);
      }

      if (mutation.type === "attributes") {
        translateElementAttributes(mutation.target);
      }
    });
  });

  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "aria-label", "title"],
  });
};

export const applyLanguage = (language = "vi") => {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.body.classList.toggle("language-en", language === "en");
  ensureObserver();
  walkAndTranslate();
};
